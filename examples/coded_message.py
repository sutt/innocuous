"""A complete, self-contained coded-message example.

This example hides a short message inside text generated by a language model and
then recovers it — the two halves of the library (encode and decode) in one file
that anyone can run without downloading a GGUF model.

Why it needs no model
---------------------
`encode` and `decode` only need *token probabilities*. A real run asks a
llama.cpp model for them; this example replays a recorded log of those
probabilities (`tests/data/recorded-logits/the-king-1.log`, captured from
mistral-7b-instruct) so the output is deterministic and runs in a second.

Run it
------
    python examples/coded_message.py
    python examples/coded_message.py --message "groovy baby" --chunk-size 3

The script prints the carrier text, the hidden message recovered from it, and
exits non-zero if the round trip fails, so it also works as a smoke test.

Expected output (default arguments):

    initial prompt : Below is an iambic penatameter poem. Complete it:
                     The king
    secret message : b'hello world'
    carrier text   : ...
    decoded message: b'hello world'
    round trip     : OK

Note on the replay switch
-------------------------
`_replay_logits()` swaps the module-level LLM helpers used by the encoder and
decoder for their recorded counterparts. That is the same mechanism the test
suite uses (`tests/test_replay_v1.py`); with a real model you would simply omit
it and pass `--llm-path /path/to/model.gguf` instead.
"""
from __future__ import annotations

import argparse
import contextlib
import os
import sys

# Importing the package pulls in llama_cpp (a hard dependency of the library);
# replay mode never calls into it, but the import must still resolve.
from stego_llm.llm.mock import MockLlama, create_mock_get_token_probabilities, mock_create_llm_client
from stego_llm.core import encoder as encoder_module
from stego_llm.core import decoder as decoder_module
from stego_llm.core import main_decode, main_encode

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_LOG = os.path.join("tests", "data", "recorded-logits", "the-king-1.log")
DEFAULT_PROMPT = "Below is an iambic penatameter poem. Complete it:\nThe king"
DEFAULT_MESSAGE = "hello world"


@contextlib.contextmanager
def _replay_logits(log_file: str):
    """Serve encoder/decoder the recorded logits instead of a live model."""
    path = log_file if os.path.isabs(log_file) else os.path.join(REPO_ROOT, log_file)
    if not os.path.exists(path):
        raise SystemExit(
            f"recorded logits not found: {path}\n"
            "Run from a checkout of the repository, or pass --log-file with an absolute path."
        )
    saved = {
        "enc_client": encoder_module.create_llm_client,
        "enc_probs": encoder_module.get_token_probabilities,
        "dec_client": decoder_module.create_llm_client,
        "dec_probs": decoder_module.get_token_probabilities,
    }
    replayer = create_mock_get_token_probabilities(version=3, log_file=os.path.basename(path))
    # create_mock_get_token_probabilities resolves logs relative to the repo root;
    # make that explicit so the example also works from another cwd.
    cwd = os.getcwd()
    os.chdir(REPO_ROOT)
    try:
        encoder_module.create_llm_client = mock_create_llm_client
        encoder_module.get_token_probabilities = replayer
        decoder_module.create_llm_client = mock_create_llm_client
        decoder_module.get_token_probabilities = replayer
        yield
    finally:
        encoder_module.create_llm_client = saved["enc_client"]
        encoder_module.get_token_probabilities = saved["enc_probs"]
        decoder_module.create_llm_client = saved["dec_client"]
        decoder_module.get_token_probabilities = saved["dec_probs"]
        os.chdir(cwd)


def run(initial_prompt: str, message: bytes, chunk_size: int, num_logprobs: int, log_file: str) -> int:
    print(f"initial prompt : {initial_prompt!r}")
    print(f"secret message : {message!r}")
    print(f"chunk size     : {chunk_size} bytes   num_logprobs: {num_logprobs}")

    with _replay_logits(log_file):
        carrier = main_encode(
            initial_prompt,
            message,
            chunk_size=chunk_size,
            num_logprobs=num_logprobs,
        )
        if not carrier:
            print("encode produced no carrier text", file=sys.stderr)
            return 2
        print(f"carrier text   : {carrier!r}")

        recovered = main_decode(
            carrier,
            initial_prompt,
            chunk_size=chunk_size,
            num_logprobs=num_logprobs,
        )

    print(f"decoded message: {recovered!r}")
    if recovered == message:
        print("round trip     : OK")
        return 0
    print("round trip     : FAILED", file=sys.stderr)
    return 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Encode a message into LLM-generated text and decode it again, without a model file."
    )
    ap.add_argument("--prompt", default=DEFAULT_PROMPT, help="carrier prompt the model continues")
    ap.add_argument("--message", default=DEFAULT_MESSAGE, help="text to hide")
    ap.add_argument("--chunk-size", type=int, default=2, help="bytes encoded per generated token")
    ap.add_argument("--num-logprobs", type=int, default=100, help="candidate tokens per step")
    ap.add_argument("--log-file", default=DEFAULT_LOG, help="recorded logits to replay")
    a = ap.parse_args(argv)
    return run(a.prompt, a.message.encode(), a.chunk_size, a.num_logprobs, a.log_file)


if __name__ == "__main__":
    raise SystemExit(main())
